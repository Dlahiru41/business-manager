-- The print agent's own embedded database (H2 file in agent.data-dir): every print request is kept here before it is
-- printed, so none is lost while the printer or the cloud is away.

CREATE TABLE print_request (
    id                    UUID PRIMARY KEY,
    seq                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    source                VARCHAR(10) NOT NULL,   -- LOCAL (the till) or CLOUD (a print job)
    cloud_job_id          UUID UNIQUE,            -- the print job, for CLOUD requests
    document              BLOB NOT NULL,          -- ESC/POS bytes, rendered when the request arrived
    status                VARCHAR(10) NOT NULL,   -- QUEUED, PRINTED or FAILED (CLOUD only)
    attempts              INT DEFAULT 0 NOT NULL,
    next_attempt_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error            VARCHAR(500),
    result_printer_status VARCHAR(10),            -- the printer's status reported with the result
    reported              BOOLEAN DEFAULT FALSE NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_print_request_source CHECK (source IN ('LOCAL', 'CLOUD')),
    CONSTRAINT ck_print_request_status CHECK (status IN ('QUEUED', 'PRINTED', 'FAILED'))
);

CREATE INDEX ix_print_request_queued ON print_request (status, seq);

CREATE TABLE cached_template (
    id         INT PRIMARY KEY,
    version    BIGINT NOT NULL,
    body       CLOB NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL
);
